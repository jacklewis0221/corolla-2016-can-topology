const tires = (tread: [number, number, number, number], psi: [number, number, number, number]): InspectionItem[] => {
  const pos = ['LF', 'RF', 'LR', 'RR'];
  return pos.map((p, i) => ({
    id: `tire${p}`,
    group: 'Tires' as const,
    label: `${p} tire`,
    value: `${tread[i]}/32 in · ${psi[i] > 0 ? `${psi[i]} psi` : 'no reading'}`,
    status: (tread[i] <= 3 ? 'now' : tread[i] <= 5 ? 'soon' : 'ok') as Health,
    note: tread[i] <= 5 ? 'Tread getting low' : undefined,
  }));
};

