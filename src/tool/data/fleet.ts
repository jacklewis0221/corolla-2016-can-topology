// Sample shop data for the service console concept. Every vehicle, customer, VIN fragment, repair order,
// mileage, price and history entry below is invented for illustration. The vehicles are E170 Corollas
// (2014–2016), the platform documented on the atlas page.

export type PresetKey = 'base' | 'plus' | 'eco';
export type ScenarioId = 'misfire' | 'lean' | 'canSkid' | 'battery' | 'maint' | 'tpms' | 'acLow' | 'ready';
export type JobStatus = 'road' | 'diagnosing' | 'maintenance' | 'waiting' | 'ready';
export type Health = 'ok' | 'soon' | 'now';

export interface Visit {
  date: string;
  miles: number;
  ro: string;
  kind: 'maintenance' | 'repair' | 'tires' | 'customer' | 'inspection';
  title: string;
  items: string[];
  finding?: string;
  total?: number;
}

export interface InspectionItem {
  id: string;
  group: 'Tires' | 'Brakes' | 'Battery' | 'Fluids' | 'Filters' | 'Wipers & lights' | 'Under vehicle';
  label: string;
  value: string;
  status: Health;
  note?: string;
  /** Sample price for the recommended work, in US dollars. */
  price?: number;
  job?: string;
}

export interface Vehicle {
  id: string;
  slot: string;
  year: 2014 | 2015 | 2016;
  trim: string;
  preset: PresetKey;
  engine: '2ZR-FE' | '2ZR-FAE';
  color: string;
  swatch: string;
  vin8: string;
  plate: string;
  miles: number;
  inService: string;
  customer: string;
  advisor: string;
  tech: string;
  /** Who holds exclusive control (active tests, clears, utilities) when the console opens. */
  holder: string;
  /** Default adapter mode: listen-only never transmits; read allows diagnostic requests. */
  mode: 'listen' | 'read';
  ro: string;
  promised: string;
  concern: string;
  status: JobStatus;
  scenario: ScenarioId;
  adapter: { id: string; ap: 'AP-1' | 'AP-2' | 'AP-3'; rssi: number; latency: number };
  history: Visit[];
  inspection: InspectionItem[];
}

